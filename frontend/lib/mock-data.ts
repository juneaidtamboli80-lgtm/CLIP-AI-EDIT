function buildWords(text: string, start: number, end: number) {
  const parts = text.split(/\s+/).filter(Boolean)
  const step = (end - start) / Math.max(parts.length, 1)
  return parts.map((word, index) => ({
    text: word,
    start: Number((start + index * step).toFixed(2)),
    end: Number((start + (index + 1) * step).toFixed(2)),
  }))
}

function cue(id: string, start: number, end: number, speaker: string, text: string): TranscriptCue {
  return { id, start, end, speaker, text, words: buildWords(text, start, end) }
}

